#python program to demonstrate string creation and basic operations (concatenation, repetition, slicing)
a = "Hello"
b = "World"
c = a + " " + b  # Concatenation
d = a * 3  # Repetition
e = a[0:3]  # Slicing
print("Concatenated string:", c)
print("Repeated string:", d)
print("Sliced string:", e)